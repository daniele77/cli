#ifndef CLI_FREEFORMCOMMAND_H
#define CLI_FREEFORMCOMMAND_H

#include <memory>
#include <string>
#include <utility>
#include <vector>

#include "command.h"
#include "select.h"

namespace cli
{
    template <typename F>
    class FreeformCommand : public Command
    {
    public:
        FreeformCommand(const FreeformCommand&) = delete;
        FreeformCommand& operator=(const FreeformCommand&) = delete;

        FreeformCommand(
            const std::string& _name,
            F fun,
            std::string desc,
            std::vector<std::string> parDesc)
            : Command(_name), func(std::move(fun)), description(std::move(desc)), parameterDesc(std::move(parDesc))
        {
        }

        bool Exec(const std::vector<std::string>& cmdLine, CliSession& session) override;
        void Help(detail::HelpGroup& entries) const override;

    private:
        const F func;
        const std::string description;
        std::vector<std::string> parameterDesc;
    };
}

#endif // CLI_FREEFORMCOMMAND_H
