namespace cli
{
    class CliSession
    {
    public:
        CliSession(Cli& _cli, std::ostream& _out, std::size_t historySize = 100);
        virtual ~CliSession() noexcept;

        CliSession(const CliSession&) = delete;
        CliSession& operator=(const CliSession&) = delete;
        CliSession(CliSession&&) = delete;
        CliSession& operator=(CliSession&&) = delete;

        void Feed(const std::string& cmd);
        void Prompt();
        void Current(Menu* menu);
        std::ostream& OutStream() { return out; }
        void Help() const;
        void Help(const std::string& commandName) const;

        void Enter()
        {
            cli.EnterAction(out);
            if (enterAction)
                enterAction(out);
        }

        void Exit()
        {
            exitAction(out);
            cli.ExitAction(out);

            auto cmds = history.GetCommands();
            cli.StoreCommands(cmds);

            exit = true;
        }

        void EnterAction(const std::function<void(std::ostream&)>& action)
        {
            enterAction = action;
        }

        void ExitAction(const std::function<void(std::ostream&)>& action)
        {
            exitAction = action;
        }

        void ShowHistory() const { history.Show(out); }

        void ExecFromHistory(unsigned index)
        {
            history.ForgetLatest();
            const auto cmd = history.At(index);
            Feed(cmd);
        }

        std::string PreviousCmd(const std::string& line)
        {
            return history.Previous(line);
        }

        std::string NextCmd()
        {
            return history.Next();
        }

        std::vector<std::string> GetCompletions(std::string currentLine) const;

    protected:
        virtual std::size_t TerminalWidth() const { return 80; }

    private:
        Cli& cli;
        std::shared_ptr<cli::OutStream> coutPtr;
        Menu* current;
        std::unique_ptr<Menu> globalScopeMenu;
        std::ostream& out;
        std::function<void(std::ostream&)> enterAction = [](std::ostream&) noexcept {};
        std::function<void(std::ostream&)> exitAction = [](std::ostream&) noexcept {};
        detail::History history;
        bool exit{false};
    };

    inline CliSession::CliSession(Cli& _cli, std::ostream& _out, std::size_t historySize) :
        cli(_cli),
        coutPtr(Cli::CoutPtr()),
        current(cli.RootMenu()),
        globalScopeMenu(std::make_unique<Menu>()),
        out(_out),
        history(historySize)
    {
        history.LoadCommands(cli.GetCommands());

        coutPtr->Register(out);
        globalScopeMenu->Insert(
            cli.GetMessages().helpName,
            {cli.GetMessages().helpArgName},
            [this](std::ostream&, const std::vector<std::string>& args)
            {
                if (args.empty())
                    Help();
                else if (args.size() == 1)
                    Help(args.front());
                else
                    out << cli.GetMessages().helpUsage << '\n';
            },
            cli.GetMessages().helpCommand
        );
        globalScopeMenu->Insert(
            cli.GetMessages().exitName,
            [this](std::ostream&) { Exit(); },
            cli.GetMessages().exitCommand
        );
        globalScopeMenu->Insert(
            cli.GetMessages().historyName,
            [this](std::ostream&) { ShowHistory(); },
            cli.GetMessages().historyCommand
        );
        globalScopeMenu->Insert(
            "!",
            {cli.GetMessages().historyIndexArg},
            [this](std::ostream&, unsigned cmdIndex) { ExecFromHistory(cmdIndex); },
            cli.GetMessages().historyExecCommand
        );
    }

    inline void CliSession::Feed(const std::string& cmd)
    {
        std::vector<std::string> strs;
        detail::split(strs, cmd);
        if (strs.empty()) return;

        history.NewCommand(cmd);

        try
        {
            bool found = globalScopeMenu->ScanCmds(strs, *this);
            if (!found) found = current->ScanCmds(strs, *this);
            if (!found)
                cli.WrongCommandHandler(out, cmd);
        }
        catch (const std::exception& e)
        {
            cli.StdExceptionHandler(out, cmd, e);
        }
        catch (...)
        {
            out << cli.GetMessages().unknownException << cmd << "\"\n";
        }
    }

    inline void CliSession::Prompt()
    {
        if (exit) return;
        out << beforePrompt
            << current->Prompt()
            << afterPrompt
            << "> "
            << std::flush;
    }

    inline void CliSession::Help() const
    {
        detail::HelpGroup global, local;
        globalScopeMenu->MainHelp(global);
        current->MainHelp(local);

        // GCC 15 emits a false-positive -Wstrict-overflow warning inside <bits/stl_tempbuf.h>
        // during std::stable_sort's temporary buffer creation. Since -Werror is enabled,
        // we suppress the warning locally for this call.
        #pragma GCC diagnostic push
        #pragma GCC diagnostic ignored "-Wstrict-overflow"

        std::stable_sort(local.begin(), local.end(),
            [](const detail::HelpEntry& a, const detail::HelpEntry& b) { return a.name < b.name; });

        #pragma GCC diagnostic pop

        detail::HelpGroup commands, menus;
        for (auto& e : local)
            (e.isMenu ? menus : commands).push_back(std::move(e));

        out << cli.GetMessages().helpHeader;
        detail::PrintHelp(out, {global, commands, menus}, TerminalWidth());
    }

    inline void CliSession::Help(const std::string& commandName) const
    {
        detail::HelpGroup matches;
        auto appendMatches = [&](const detail::HelpGroup& entries)
        {
            for (const auto& entry : entries)
                if (entry.name == commandName)
                    matches.push_back(entry);
        };

        detail::HelpGroup global, local;
        globalScopeMenu->MainHelp(global);
        current->MainHelp(local);
        appendMatches(global);
        appendMatches(local);

        if (matches.empty())
        {
            out << cli.GetMessages().commandNotFound << commandName << '\n';
            return;
        }

        detail::PrintHelp(out, {matches}, TerminalWidth());
    }

    inline std::vector<std::string> CliSession::GetCompletions(std::string currentLine) const
    {
        currentLine.erase(currentLine.begin(), std::find_if(currentLine.begin(), currentLine.end(), [](int ch) { return !std::isspace(ch); }));
        auto v1 = globalScopeMenu->GetCompletions(currentLine);
        auto v3 = current->GetCompletions(currentLine);
        v1.insert(v1.end(), std::make_move_iterator(v3.begin()), std::make_move_iterator(v3.end()));

        std::sort(v1.begin(), v1.end());
        auto ip = std::unique(v1.begin(), v1.end());
        v1.resize(static_cast<std::size_t>(std::distance(v1.begin(), ip)));

        return v1;
    }

    template <typename F, typename ... Args>
    inline bool VariadicFunctionCommand<F, Args...>::Exec(const std::vector<std::string>& cmdLine, CliSession& session)
    {
        if (!IsEnabled()) return false;
        const std::size_t paramSize = sizeof...(Args);
        if (cmdLine.size() != paramSize + 1) return false;
        if (Name() == cmdLine[0])
        {
            try
            {
                auto g = [&](auto ... pars) { func(session.OutStream(), pars...); };
                Select<Args...>::Exec(g, std::next(cmdLine.begin()), cmdLine.end());
            }
            catch (std::bad_cast&)
            {
                return false;
            }
            return true;
        }
        return false;
    }

    template <typename F, typename ... Args>
    inline void VariadicFunctionCommand<F, Args...>::Help(detail::HelpGroup& entries) const
    {
        if (!IsEnabled()) return;
        detail::HelpEntry e;
        e.name = Name();
        e.params = parameterDesc;
        if (e.params.empty())
            ParamNames<Args...>::Collect(e.params);
        e.description = description;
        entries.push_back(std::move(e));
    }

    template <typename F>
    inline bool FreeformCommand<F>::Exec(const std::vector<std::string>& cmdLine, CliSession& session)
    {
        if (!IsEnabled()) return false;
        assert(!cmdLine.empty());
        if (Name() == cmdLine[0])
        {
            func(session.OutStream(), std::vector<std::string>(std::next(cmdLine.begin()), cmdLine.end()));
            return true;
        }
        return false;
    }

    template <typename F>
    inline void FreeformCommand<F>::Help(detail::HelpGroup& entries) const
    {
        if (!IsEnabled()) return;
        detail::HelpEntry e;
        e.name = Name();
        e.params = parameterDesc;
        if (e.params.empty())
            ParamNames<std::vector<std::string>>::Collect(e.params);
        e.description = description;
        entries.push_back(std::move(e));
    }

    inline bool Menu::HandleCommand(const std::vector<std::string>& cmdNames, const std::vector<std::string>& cmdLine, CliSession& session)
    {
        if (!IsEnabled())
            return false;

        assert(!cmdLine.empty());

        if (std::find(cmdNames.begin(), cmdNames.end(), cmdLine[0]) != cmdNames.end())
        {
            if (cmdLine.size() == 1)
            {
                session.Current(this);
                return true;
            }
            else
            {
                std::vector<std::string> subCmdLine(cmdLine.begin() + 1, cmdLine.end());
                for (auto& cmd : *cmds)
                    if (cmd->Exec(subCmdLine, session)) return true;
                return (parent && parent->ExecParent(subCmdLine, session));
            }
        }
        return false;
    }

    inline void CliSession::Current(Menu* menu)
    {
        current = menu;
        if (current)
            current->OnEnter(out);
    }

    inline CliSession::~CliSession() noexcept
    {
        coutPtr->UnRegister(out);
    }
}

#endif // CLI_CLISESSION_H_
