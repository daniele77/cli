#include <cli/cli.h>
#include <cli/clifilesession.h>

using namespace cli;
using namespace std;

int main()
{
    auto rootMenu = make_unique<Menu>("cli");

    rootMenu->Insert(
        "saluta",
        [](std::ostream& out)
        {
            out << "Ciao, mondo\n";
        },
        "Stampa un messaggio di benvenuto"
    );

    rootMenu->Insert(
        "somma",
        [](std::ostream& out, int a, int b)
        {
            out << a << " + " << b << " = " << (a + b) << "\n";
        },
        "Somma due numeri",
        {"primo numero", "secondo numero"}
    );

    Cli::Messages messages;
    messages.wrongCommand = "comando non valido: ";
    messages.unknownException = "Eccezione CLI non gestita durante l'esecuzione: \"";
    messages.helpHeader = "Comandi disponibili:\n\n";
    messages.helpUsage = "uso: aiuto [comando]";
    messages.commandNotFound = "comando non trovato: ";
    messages.helpName = "aiuto";
    messages.helpArgName = "comando";
    messages.helpCommand = "Mostra la guida";
    messages.exitName = "esci";
    messages.exitCommand = "Chiude la sessione";
    messages.historyName = "storia";
    messages.historyCommand = "Mostra la cronologia";
    messages.historyIndexArg = "indice della cronologia";
    messages.historyExecCommand = "Esegue un comando dalla cronologia";

    Cli cli(std::move(rootMenu), std::make_unique<VolatileHistoryStorage>(), messages);

    cli.ExitAction([](std::ostream& out)
    {
        out << "Arrivederci!\n";
    });

    CliFileSession session(cli);
    session.Start();

    return 0;
}
