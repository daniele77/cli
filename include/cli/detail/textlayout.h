#ifndef CLI_DETAIL_TEXTLAYOUT_H_
#define CLI_DETAIL_TEXTLAYOUT_H_
 
// Primitives to lay out text on a character terminal.
//
// This header knows nothing about menus, commands, sessions or terminals:
// it only deals with strings, widths and streams. Every piece of code that
// needs to know "how wide is this string on the screen?" must go through
// DisplayWidth(), so that when the answer changes (colors, Unicode) it
// changes in one place only.
 
#include <cstddef>
#include <ostream>
#include <string>
#include <utility>
#include <vector>
 
namespace cli
{
namespace detail
{
 
// Number of terminal columns occupied by s when printed.
//
// - ANSI CSI sequences (ESC [ ... final-byte, e.g. colors) take no space.
// - UTF-8 continuation bytes are not counted, so each code point counts as 1.
//
// Known limits: East Asian wide characters (2 columns), combining characters
// (0 columns) and control characters such as '\t' are not handled.
inline std::size_t DisplayWidth(const std::string& s)
{
    std::size_t width = 0;
    for (std::size_t i = 0; i < s.size(); ++i)
    {
        const auto c = static_cast<unsigned char>(s[i]);
        if (c == 0x1B && i + 1 < s.size() && s[i + 1] == '[')
        {
            i += 2;
            // parameters and intermediate bytes, up to the final byte (0x40-0x7E)
            while (i < s.size() &&
                   !(static_cast<unsigned char>(s[i]) >= 0x40 &&
                     static_cast<unsigned char>(s[i]) <= 0x7E))
                ++i;
            // now i is on the final byte (or past the end): the loop's ++i skips it
        }
        else if ((c & 0xC0) != 0x80) // not a UTF-8 continuation byte
        {
            ++width;
        }
    }
    return width;
}
 
// Writes n spaces.
inline void Spaces(std::ostream& out, std::size_t n)
{
    out << std::string(n, ' ');
}
 
// Writes s, followed by as many spaces as needed to reach `width` columns.
// If s is already wider than `width`, no padding is written.
inline void PadRight(std::ostream& out, const std::string& s, std::size_t width)
{
    out << s;
    const std::size_t w = DisplayWidth(s);
    if (w < width)
        Spaces(out, width - w);
}
 
namespace textlayout_impl
{
    inline bool IsBlank(char c) { return c == ' ' || c == '\t' || c == '\r'; }
 
    inline void WrapParagraph(const std::string& p,
                              std::size_t width,
                              std::vector<std::string>& lines)
    {
        std::string line;
        std::size_t lineWidth = 0;
        bool anyWord = false;
 
        std::size_t i = 0;
        while (i < p.size())
        {
            while (i < p.size() && IsBlank(p[i])) ++i;
            const std::size_t begin = i;
            while (i < p.size() && !IsBlank(p[i])) ++i;
            if (begin == i) break;
 
            const std::string word = p.substr(begin, i - begin);
            const std::size_t w = DisplayWidth(word);
 
            if (!line.empty() && lineWidth + 1 + w > width)
            {
                lines.push_back(std::move(line));
                line.clear();
                lineWidth = 0;
            }
            if (!line.empty())
            {
                line += ' ';
                ++lineWidth;
            }
            line += word;
            lineWidth += w;
            anyWord = true;
        }
 
        if (!line.empty())
            lines.push_back(std::move(line));
        else if (!anyWord)
            lines.push_back(std::string()); // blank paragraph -> blank line
    }
} // namespace textlayout_impl
 
// Splits text into lines of at most `width` columns, breaking on blanks.
//
// - A word wider than `width` is not broken: it gets a line of its own.
// - Runs of blanks collapse into a single space.
// - A '\n' in text forces a line break (an empty paragraph gives an empty line).
// - An empty text gives no lines at all.
inline std::vector<std::string> Wrap(const std::string& text, std::size_t width)
{
    std::vector<std::string> lines;
    if (text.empty())
        return lines;
 
    std::size_t start = 0;
    for (;;)
    {
        const std::size_t end = text.find('\n', start);
        const std::size_t len = (end == std::string::npos) ? std::string::npos : end - start;
        textlayout_impl::WrapParagraph(text.substr(start, len), width, lines);
        if (end == std::string::npos)
            break;
        start = end + 1;
    }
    return lines;
}

} // namespace detail
} // namespace cli
 
#endif // CLI_DETAIL_TEXTLAYOUT_H_