#include "volatilehistorystorage.h"

namespace cli
{
    class Menu;
    class CliSession;

    class Cli
    {
    public:
        struct Messages
        {
            std::string wrongCommand;
            std::string unknownException;
            std::string helpHeader;
            std::string helpUsage;
            std::string commandNotFound;
            std::string helpName;
            std::string helpArgName;
            std::string helpCommand;
            std::string exitName;
            std::string exitCommand;
            std::string historyName;
            std::string historyCommand;
            std::string historyIndexArg;
            std::string historyExecCommand;

            Messages() :
                wrongCommand("wrong command: "),
                unknownException("Cli. Unknown exception caught handling command line \""),
                helpHeader("Commands available:\n\n"),
                helpUsage("usage: help [command]"),
                commandNotFound("command not found: "),
                helpName("help"),
                helpArgName("command"),
                helpCommand("This help message"),
                exitName("exit"),
                exitCommand("Quit the session"),
                historyName("history"),
                historyCommand("Show the history"),
                historyIndexArg("history entry index"),
                historyExecCommand("Exec a command by index in the history")
            {
            }
        };

        ~Cli() = default;
        Cli(const Cli&) = delete;
        Cli& operator=(const Cli&) = delete;
        Cli(Cli&&) = default;
        Cli& operator=(Cli&&) = default;

        Cli(std::unique_ptr<Menu> _rootMenu,
            std::unique_ptr<HistoryStorage> historyStorage = std::make_unique<VolatileHistoryStorage>(),
            Messages _messages = Messages{});
        Cli(std::unique_ptr<Menu> _rootMenu,
            Messages _messages,
            std::unique_ptr<HistoryStorage> historyStorage = std::make_unique<VolatileHistoryStorage>());

        void EnterAction(const std::function<void(std::ostream&)>& action) { enterAction = action; }
        void ExitAction(const std::function<void(std::ostream&)>& action) { exitAction = action; }

        void StdExceptionHandler(const std::function<void(std::ostream&, const std::string& cmd, const std::exception&)>& handler)
        {
            exceptionHandler = handler;
        }

        void WrongCommandHandler(const std::function<void(std::ostream&, const std::string& cmd)>& handler)
        {
            wrongCmdHandler = handler;
        }

        void SetMessages(const Messages& _messages)
        {
            messages = _messages;
        }

        const Messages& GetMessages() const
        {
            return messages;
        }

        static OutStream& cout()
        {
            return *CoutPtr();
        }

    private:
        friend class CliSession;

        static std::shared_ptr<OutStream> CoutPtr()
        {
            static std::shared_ptr<OutStream> s = std::make_shared<OutStream>();
            return s;
        }

        Menu* RootMenu() { return rootMenu.get(); }

        void EnterAction(std::ostream& out)
        {
            if (enterAction)
                enterAction(out);
        }

        void ExitAction(std::ostream& out)
        {
            if (exitAction)
                exitAction(out);
        }

        void StdExceptionHandler(std::ostream& out, const std::string& cmd, const std::exception& e)
        {
            if (exceptionHandler)
                exceptionHandler(out, cmd, e);
            else
                out << e.what() << '\n';
        }

        void WrongCommandHandler(std::ostream& out, const std::string& cmd)
        {
            if (wrongCmdHandler)
                wrongCmdHandler(out, cmd);
            else
                out << messages.wrongCommand << cmd << '\n';
        }

        void StoreCommands(const std::vector<std::string>& cmds)
        {
            globalHistoryStorage->Store(cmds);
        }

        std::vector<std::string> GetCommands() const
        {
            return globalHistoryStorage->Commands();
        }

    private:
        std::unique_ptr<HistoryStorage> globalHistoryStorage;
        std::unique_ptr<Menu> rootMenu;
        std::function<void(std::ostream&)> enterAction;
        std::function<void(std::ostream&)> exitAction;
        std::function<void(std::ostream&, const std::string& cmd, const std::exception&)> exceptionHandler;
        std::function<void(std::ostream&, const std::string& cmd)> wrongCmdHandler;
        Messages messages;
    };

    inline Cli::Cli(std::unique_ptr<Menu> _rootMenu,
        std::unique_ptr<HistoryStorage> historyStorage,
        Messages _messages) :
        globalHistoryStorage{std::move(historyStorage)},
        rootMenu{std::move(_rootMenu)},
        enterAction{},
        exitAction{},
        messages{std::move(_messages)}
    {
    }

    inline Cli::Cli(std::unique_ptr<Menu> _rootMenu,
        Messages _messages,
        std::unique_ptr<HistoryStorage> historyStorage) :
        Cli(std::move(_rootMenu), std::move(historyStorage), std::move(_messages))
    {
    }
}

